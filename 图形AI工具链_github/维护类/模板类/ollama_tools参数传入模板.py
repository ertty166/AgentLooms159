# 【Tools 根列表】
# Ollama 接受一个工具列表，你可以在这里放入多个工具的定义
tools = [
    # 【单个工具定义开始】
    # 每一个工具都是一个字典
    {
        # 【类型声明】
        # 固定写死为 "function"
        # 告诉 Ollama 这是一个函数工具（目前 Ollama 主要支持函数调用）
        "type": "function",
        # 【函数主体】
        # 这个键对应的值是工具的具体定义
        "function": {
            # 【工具名称】
            # 必须是字符串，只能包含字母、数字和下划线，不能有空格
            # 模型在决定调用哪个工具时，会使用这个名字
            "name": "get_time_and_location",
            # 【工具描述】
            # 模型“看”这个描述来决定是否调用该工具
            # 描述越清晰，模型判断越准确。这里告诉模型这个工具是用来获取时间地点的
            "description": "获取用户当前所在的地理位置以及当前的精确时间，用于提供基于时间和地点的上下文服务",
            # 【参数定义】
            # 定义这个工具需要接收什么参数
            "parameters": {
                # 【参数对象类型】
                # JSON Schema 规范，固定为 "object" 表示参数是一个对象
                "type": "object",
                # 【属性定义】
                # 定义具体的参数字段。
                # 因为我们要提供的是“当前”的时间地点，不需要用户输入任何参数，
                # 所以这里保持为空字典 {}。
                # 如果工具需要参数（如经纬度），则在这里定义字段名和类型。
                "properties": {},
                # 【必填项列表】
                # 定义哪些属性是必须提供的。
                # 因为我们不需要用户输入参数，所以这里也是空列表 []。
                "required": []
            }
        }
    }
    # 【单个工具定义结束】
]
# 【Tools 根列表结束】