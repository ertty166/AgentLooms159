    def _获取字段值(self, 协议包: dict, 字段路径: str) -> any:
        """根据点分隔路径获取字段值，路径不存在返回 None"""
        if not 协议包 or not isinstance(协议包, dict):
            return None
        
        路径列表 = 字段路径.split(".")
        当前层级 = 协议包
        
        for 层级名 in 路径列表:
            if not isinstance(当前层级, dict):
                return None
            当前层级 = 当前层级.get(层级名)
            if 当前层级 is None:
                return None
        
        return 当前层级
    
    def _设置字段值(self, 协议包: dict, 字段路径: str, 新值: any, 自动创建: bool = True) -> bool:
        """根据点分隔路径设置字段值，自动创建缺失的中间层级"""
        if not 协议包 or not isinstance(协议包, dict):
            return False
        
        路径列表 = 字段路径.split(".")
        当前层级 = 协议包
        
        # 遍历到倒数第二层
        for 层级名 in 路径列表[:-1]:
            if 层级名 not in 当前层级:
                if not 自动创建:
                    return False
                当前层级[层级名] = {}
            elif not isinstance(当前层级[层级名], dict):
                if not 自动创建:
                    return False
                当前层级[层级名] = {}
            当前层级 = 当前层级[层级名]
        
        # 设置最终值
        最终层级名 = 路径列表[-1]
        当前层级[最终层级名] = 新值
        return True
    
    def _删除字段值(self, 协议包: dict, 字段路径: str) -> bool:
        """根据点分隔路径删除字段值，成功返回 True，不存在也返回 True（幂等）"""
        if not 协议包 or not isinstance(协议包, dict):
            return False
        
        路径列表 = 字段路径.split(".")
        当前层级 = 协议包
        
        # 遍历到倒数第二层
        for 层级名 in 路径列表[:-1]:
            if not isinstance(当前层级, dict) or 层级名 not in 当前层级:
                return True
            当前层级 = 当前层级[层级名]
        
        # 删除最终值
        最终层级名 = 路径列表[-1]
        if isinstance(当前层级, dict) and 最终层级名 in 当前层级:
            del 当前层级[最终层级名]
        return True
    # ========== 四层处理核心方法（参考插件公用类） ==========
    def _处理字段(self, 协议包: dict, 字段路径: str, 新值: any, 
                  强制策略: str = None) -> tuple:
        """
        四层处理：优先修改 → 优先透传 → 优先销毁 → 强制修改
        
        返回: (成功否: bool, 消息: str)
        成功时直接修改传入的协议包（引用修改）
        """
        # 确定策略
        策略 = 强制策略 if 强制策略 else self.字段策略.get(字段路径, "优先修改")
        当前值 = self._获取字段值(协议包, 字段路径)
        
        # ========== 第1层: 优先修改 ==========
        if 策略 == "优先修改":
            # 尝试修改，无论当前值是否存在
            成功 = self._设置字段值(协议包, 字段路径, 新值, 自动创建=True)
            if 成功:
                return True, f"优先修改成功: {字段路径}"
            # 修改失败，进入优先透传
            if 当前值 is not None:
                return True, f"优先修改失败，透传原值: {字段路径}"
            # 透传也没值，进入优先销毁
        
        # ========== 第2层: 优先透传 ==========
        elif 策略 == "优先透传":
            if 当前值:
                # 有值就透传，不修改
                return True, f"优先透传成功: {字段路径}"
            # 没值，尝试用新值修改（这就是用户要求的：优先透传在无值时按正常逻辑新建）
            成功 = self._设置字段值(协议包, 字段路径, 新值, 自动创建=True)
            if 成功:
                return True, f"优先透传(原值空，已新建): {字段路径}"
            # 修改也失败，进入优先销毁
        
        # ========== 第3层: 优先销毁 ==========
        elif 策略 == "优先销毁":
            self._删除字段值(协议包, 字段路径)
            self._设置字段值(协议包, 字段路径, None, 自动创建=True)
            return True, f"优先销毁成功: {字段路径}"
        
        # ========== 第4层: 强制修改 ==========
        elif 策略 == "强制修改":
            成功 = self._设置字段值(协议包, 字段路径, 新值, 自动创建=True)
            if 成功:
                return True, f"强制修改成功: {字段路径}"
            return False, f"强制修改失败: {字段路径}"
        
        else:
            return False, f"未知策略: {策略}"
        
        # 兜底：如果前面没返回，尝试销毁
        self._删除字段值(协议包, 字段路径)
        self._设置字段值(协议包, 字段路径, None, 自动创建=True)
        return True, f"兜底销毁: {字段路径}"
    
    def _批量处理字段(self, 协议包: dict, 字段列表: list) -> tuple:
        """
        批量处理多个字段
        字段列表: [(字段路径, 新值, 强制策略), ...] 或 [(字段路径, 新值), ...]
        返回: (全部成功否: bool, 详细结果: list, 修改后新协议包(修改没成功会保持原包):dict)
        """
        新协议包 = copy.deepcopy(协议包)
        详细结果 = []
        全部成功 = True
        
        for 字段项 in 字段列表:
            if len(字段项) == 2:
                字段路径, 新值 = 字段项
                强制策略 = None
            else:
                字段路径, 新值, 强制策略 = 字段项
            
            成功, 消息 = self._处理字段(新协议包, 字段路径, 新值, 强制策略=强制策略)
            详细结果.append((字段路径, 成功, 消息))
            if not 成功:
                全部成功 = False
        
        return 全部成功, 详细结果, 新协议包

    def _获取或创建会话(self, 节点ID: str, 偏好会话标识: str = None,
                        创建者: str = None) -> tuple[str, Optional["消息树管理器.会话状态"]]:
        """
        【20260427】统一的会话获取/创建入口
        优先级：偏好会话标识 > 节点当前会话 > 新建
        返回: (会话标识, 会话状态对象)
        注意：此方法内部已上锁，调用方无需额外加锁
        """
        with self._图谱锁:
            # 1. 尝试使用偏好会话标识
            if 偏好会话标识 and 偏好会话标识 in self._会话图谱:
                return 偏好会话标识, self._会话图谱[偏好会话标识]
            
            # 2. 尝试使用节点当前绑定的会话
            节点会话 = self._节点会话表.get(节点ID)
            if 节点会话 and 节点会话 in self._会话图谱:
                return 节点会话, self._会话图谱[节点会话]
            
            # 3. 新建会话
            创建者 = 创建者 or 节点ID or "系统"
            新标识 = self._生成会话标识(创建者)
            会话 = self.会话状态(新标识, 创建者)
            self._会话图谱[新标识] = 会话
            self._节点会话表[节点ID] = 新标识
            return 新标识, 会话
    
    def _绑定节点会话(self, 节点ID: str, 会话标识: str):
        """【20260427】统一绑定节点到会话（需上锁）"""
        if not (节点ID and 会话标识):
            return
        with self._图谱锁:
            self._节点会话表[节点ID] = 会话标识
            会话 = self._会话图谱.get(会话标识)
            if isinstance(会话, self.会话状态):
                会话.参与节点.add(节点ID)
    
    def _解绑节点会话(self, 节点ID: str, 会话标识: str = None) -> bool:
        """
        【20260427】解绑节点与会话（需上锁）
        如果指定会话标识，只有匹配时才解绑
        返回是否成功解绑
        """
        with self._图谱锁:
            当前绑定 = self._节点会话表.get(节点ID)
            if not 当前绑定:
                return False
            if 会话标识 and 当前绑定 != 会话标识:
                return False
            del self._节点会话表[节点ID]
            return True
    
    def _取会话绑定节点(self, 会话标识: str) -> List[str]:
        """【20260427】获取绑定到某个会话的所有节点（需上锁）"""
        with self._图谱锁:
            return [nid for nid, sid in self._节点会话表.items() if sid == 会话标识]
    
    def _状态_判断并增加会话消息(self, 消息标识: str, 会话标识: str):
        """【20260502】绑定会话与某消息（需上锁）"""
        if not (消息标识 and 会话标识):
            return
        with self._图谱锁:
            会话 = self._会话图谱.get(会话标识, None)
            if isinstance(会话, self.会话状态):
                消息 = 会话.具有消息.get(消息标识, None)
                if 消息 is None:
                    会话.具有消息[消息标识] = {}   
    
    def _状态_标记消息标识运行中(self, 消息标识: str, 会话标识: str, 节点ID: str):
        """
        节点标记某消息进入"运行中"状态
        逻辑：为此节点ID创建/更新 (False, None) 记录
        """
        if not (消息标识 and 会话标识 and 节点ID):
            return
        # with self._图谱锁:
        会话 = self._会话图谱.get(会话标识)
        if not isinstance(会话, self.会话状态):
            return
        
        # 初始化这个消息标识的字典
        if 消息标识 not in 会话.具有消息:
            with self._图谱锁:
                会话.具有消息[消息标识] = {}
        
        # 此节点标记运行中（False=运行中, None=尚未完成）
        with self._图谱锁:
            会话.具有消息[消息标识][节点ID] = (False, None)
        
        日志.调试(f"消息 {消息标识} 节点 {节点ID} 标记运行中", 节点ID)

    def _状态_标记消息标识已处理(self, 消息标识: str, 会话标识: str, 节点ID: str):
        """
        节点标记某消息处理完成
        逻辑：将此节点ID的记录改为 (False, True)
        """
        if not (消息标识 and 会话标识 and 节点ID):
            return
        # with self._图谱锁:
        会话 = self._会话图谱.get(会话标识)
        if not isinstance(会话, self.会话状态):
            return
        
        节点字典 = 会话.具有消息.get(消息标识, {})
        if 节点ID not in 节点字典:
            日志.警告(f"消息 {消息标识} 节点 {节点ID} 没有运行中记录，直接标记完成", 节点ID)
            # 容错：没有运行中也允许标记完成（异常流程）
            if 消息标识 not in 会话.具有消息:
                with self._图谱锁:
                    会话.具有消息[消息标识] = {}
            with self._图谱锁:
                会话.具有消息[消息标识][节点ID] = (False, True)
            return
        
        # 标记此节点处理完成
        运行中状态, _ = 节点字典[节点ID]
        with self._图谱锁:
            节点字典[节点ID] = (运行中状态, True)
        
        日志.调试(f"消息 {消息标识} 节点 {节点ID} 标记处理完成", 节点ID)

    def _状态_判断并标记消息完成(self, 消息标识: str, 会话标识: str) -> bool:
        """
        判断某消息标识是否全部处理完毕，是则加入完成列表
        
        逻辑链条：
        1. 取出该消息标识下的所有节点处理记录
        2. 检查每个节点的元组是否为 (False, True) —— 先运行中后完成
        3. 检查节点数量是否符合消息分片总数（如果有分片）
           - 有分片：节点数 == 分片总数（总共+1）
           - 无分片：节点数 == 1（单节点处理）
        4. 全部通过 → 加入完成消息列表
        
        返回: True=该消息已完成, False=还有节点未处理完或数量不对
        """
        if not (消息标识 and 会话标识):
            return False
        with self._图谱锁:
            会话 = self._会话图谱.get(会话标识)
            if not isinstance(会话, self.会话状态):
                return False
            
            节点字典 = 会话.具有消息.get(消息标识)
            if not 节点字典:
                return False  # 没有记录
            
            # 检查1：每个节点都必须是 (False, True) —— 先运行中后完成
            未完成节点 = []
            for 节点ID, (运行中, 完成) in 节点字典.items():
                if not (运行中 == False and 完成 == True):
                    未完成节点.append(节点ID)
            
            if 未完成节点:
                日志.调试(f"消息 {消息标识} 节点 {未完成节点} 尚未完成处理")
                return False
            
            # 检查2：节点数量是否符合预期
            原始协议包 = 会话.消息字典.get(消息标识, {})
            消息分片 = self._获取字段值(原始协议包, "协议尾.消息分片")
            
            实际节点数 = len(节点字典)
            
            if isinstance(消息分片, dict):
                # 有分片：节点数应等于分片总数（总共+1，因为"总共"是最大索引）
                预期节点数 = 消息分片.get("总共", 0) + 1
                if 实际节点数 != 预期节点数:
                    日志.调试(f"消息 {消息标识} 节点数 {实际节点数} != 分片总数 {预期节点数}")
                    return False
            else:
                # 无分片：节点数应为1（单节点处理此消息）
                if 实际节点数 != 1:
                    日志.调试(f"消息 {消息标识} 无分片但节点数 {实际节点数} != 1,可能还有节点未上报")
                    return False
            
            # 全部检查通过，标记完成
            if 消息标识 not in 会话.完成消息:
                会话.完成消息.append(消息标识)
                日志.调试(f"消息 {消息标识} 全部 {实际节点数} 个节点处理完成,已加入完成列表")
            
            return True

