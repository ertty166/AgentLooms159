    def 提取标记内内容(self,文本: str,标记:str = "```") -> list:
        """
        提取文本中三个反引号 ``` 之间的内容
        使用索引遍历方法：第1个和第2个配一对取中间，第3个和第4个配一对取中间
        如果最后剩一个则舍弃
        返回: 按出现顺序排列的反引号块内容列表
        """
        标记长度 = len(标记)
        所有索引 = []
        当前位置 = 0
        # 第一步：遍历记录所有反引号标记的索引位置
        while True:
            找到位置 = 文本.find(标记, 当前位置)
            if 找到位置 == -1:
                break
            所有索引.append(找到位置)
            当前位置 = 找到位置 + 标记长度
        # 第二步：配对提取（第1个和第2个配一对，第3个和第4个配一对...）
        内容列表 = []
        索引计数 = len(所有索引)
        # 成对遍历：步长为2，每次取当前和下一个
        for 起始指针 in range(0, 索引计数 - 1, 2):
            起始位置 = 所有索引[起始指针]
            结束位置 = 所有索引[起始指针 + 1]
            # 提取中间内容（从第一个标记结束位置到第二个标记开始位置）
            块起始 = 起始位置 + 标记长度
            块内容 = 文本[块起始:结束位置]
            内容列表.append(块内容.strip())
        # 如果最后剩一个索引（奇数个），自动舍弃
        return 内容列表

