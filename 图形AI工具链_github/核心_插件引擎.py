    def 移除标记间内容(self, 开头标记:str, 结尾标记:str, 字符串数据:str)->str:
        """移除两端包含标记本身在内的标记间内容"""
        while 开头标记 in 字符串数据 and 结尾标记 in 字符串数据:
            头 = 字符串数据.find(开头标记)
            尾 = 字符串数据.find(结尾标记, 头 + len(开头标记))
            字符串数据 = 字符串数据[:头] + 字符串数据[尾 + len(结尾标记):]
        return 字符串数据
    
