    def _取插件名(self, 文件路径: str = None) -> str: # 20260414
        """从Python文件中提取 __名称__ 字段的值"""
        if not 文件路径:
            return None
        try:
            代码 = Path(文件路径).read_text(encoding='utf-8')
            树 = ast.parse(代码)
            for 节点 in ast.walk(树):
                if isinstance(节点, ast.Assign):
                    for 目标 in 节点.targets:
                        if isinstance(目标, ast.Name) and 目标.id == "__名称__":
                            if isinstance(节点.value, ast.Constant):
                                名称 = 节点.value.value
                                return 名称 if isinstance(名称, str) else None
            return None
        except Exception:
            return None
    
    def _解析信息(self, 代码: str, 文件路径: str):
        信息 = 插件信息()
        信息.路径 = 文件路径
        信息.代码 = 代码
        try:
            树 = ast.parse(代码)
            文档 = ast.get_docstring(树)
            if 文档:
                信息.描述 = 文档.strip()
            for 节点 in ast.walk(树):
                if isinstance(节点, ast.Assign):
                    for 目标 in 节点.targets:
                        if isinstance(目标, ast.Name):
                            if 目标.id == "__名称__" and isinstance(节点.value, ast.Constant):
                                信息.名称 = 节点.value.value
                            elif 目标.id == "__版本__" and isinstance(节点.value, ast.Constant):
                                信息.版本 = 节点.value.value
                            elif 目标.id == "__作者__" and isinstance(节点.value, ast.Constant):
                                信息.作者 = 节点.value.value
                            elif 目标.id == "__分类__" and isinstance(节点.value, ast.Constant):
                                信息.分类 = 节点.value.value
                            elif 目标.id == "__关键词__" and isinstance(节点.value, ast.Constant):
                                信息.关键词 = 节点.value.value
                            elif 目标.id == "__分片策略类型__" and isinstance(节点.value, ast.Constant): # 20260428
                                分片策略类型 = 节点.value.value
                                if 分片策略类型 in self._允许分片策略类型:
                                    信息.类型 = 分片策略类型
                                else:
                                    信息.类型 = "否" # 不允许输出分片
                            elif 目标.id == "__简介__" and isinstance(节点.value, ast.JoinedStr):    
                                try:
                                    # 尝试执行代码获取f-string的值
                                    # 需要先定义这些变量
                                    本地变量 = {
                                        "__名称__": 信息.名称 or "",
                                        "__版本__": 信息.版本 or "",
                                        "__作者__": 信息.作者 or "",
                                        "__分类__": 信息.分类 or "",
                                        "__关键词__": 信息.关键词 or "",
                                    }
                                    
                                    # 执行赋值语句获取结果
                                    exec(compile(ast.Module(body=[节点], type_ignores=[]), 
                                                filename=文件路径, mode='exec'), 
                                        {}, 本地变量)
                                    
                                    信息.简介 = 本地变量.get("__简介__", "")
                                except Exception as e:
                                    # 如果执行失败，使用原始f-string的源码
                                    日志.警告(f"插件简介动态加载失败:{traceback.format_exc()}", 文件路径)
                            elif 目标.id == "__工具介绍__" and isinstance(节点.value, ast.List):
                                try:
                                    信息.工具介绍 = ast.literal_eval(节点.value)
                                except:
                                    日志.错误(f"插件名:{信息.名称},\nast加载插件树时错误:\n{traceback.format_exc()}")
                                    信息.工具介绍 = None
                            elif 目标.id == "独立运行调试" and isinstance(节点.value, ast.Constant):
                                信息.独立运行调试 = 节点.value.value
            有处理 = any(isinstance(n, ast.FunctionDef) and n.name == "处理" for n in ast.walk(树))
            if not 有处理:
                信息.错误 = "缺少处理函数"
                return 信息
            if 信息.独立运行调试 is not False:
                信息.错误 = f"独立运行调试必须是False，当前值: {信息.独立运行调试}"
                return 信息
            if not 信息.名称:
                信息.名称 = Path(文件路径).stem
            信息.有效 = True

        except SyntaxError as e:
            信息.错误 = f"语法错误: {e}"
        except Exception as e:
            信息.错误 = f"解析错误: {e}"
        
        return 信息

