    def _获取分片策略类型(self,节点ID:str)->bool:
        """根据那个节点的信息返回是否要分片他的输出,兜底True"""
        if not 节点ID:
            return None
        节点对象 = 状态.取节点对象(节点ID)
        节点类型 = getattr(节点对象, "类型", None)

        if 节点类型 == "插件":
            插件信息 = 进程管理.取插件信息(节点ID)
            分片策略类型 = 插件信息.类型

