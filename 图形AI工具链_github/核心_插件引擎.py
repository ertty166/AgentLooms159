@dataclass
class 协议包:
    """通信协议数据结构"""
    类型: str  # "输出" | "日志" | "状态" | "错误" | "事件" | "命令确认"
    数据: Any = None
    元信息: Dict = field(default_factory=dict)
    
    def to_json(self) -> str:
        return json.dumps({
            "类型": self.类型,
            "数据": self.数据,
            "元信息": self.元信息
        }, ensure_ascii=False)
    
    @classmethod
    def from_json(cls, json_str: str) -> Optional["协议包"]:
        try:
            解析 = json.loads(json_str)
            return cls(
                类型=解析.get("类型", "未知"),
                数据=解析.get("数据"),
                元信息=解析.get("元信息", {})
            )
        except:
            # 兼容旧版纯文本格式
            if json_str.startswith("[输出]"):
                return cls(类型="输出", 数据=json_str[4:])
            elif json_str.startswith("[日志]"):
                内容 = json_str[4:]
                if ":" in 内容:
                    级别, 消息 = 内容.split(":", 1)
                else:
                    级别, 消息 = "信息", 内容
                return cls(类型="日志", 数据={"级别": 级别, "消息": 消息})
            elif json_str.startswith("[状态]"):
                return cls(类型="状态", 数据=json_str[4:])
            elif json_str.startswith("[错误]"):
                return cls(类型="错误", 数据=json_str[4:])
            return None

