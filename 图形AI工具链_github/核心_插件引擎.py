    def 处理输出(self, 原始协议包: dict, 节点ID) -> Optional[list[dict]]:
        """
        处理插件输出的协议包
        - 协议包处理不上锁，类变量操作上锁
        - 【20260427】入口处调用流水线清洗，防止僵尸会话标识流传
        - 【20260428】会话生命周期严格规定：
          1. 只有"输出"类型且会话标识为空时，创建新会话
          2. "日志"类型有会话标识时参与引用计数
          3. "状态"类型有会话标识时更新引用计数（不创建）
          4. 其他类型不参与会话生命周期
        返回:
            - 完整协议包列表(可能是一个或多个)
            - None（分片不完整，已挂起保存，等待后续分片）
        """
        # 【20260427】第一步：流水线清洗会话标识（协议包修改，不上锁）
        
        
        数据类型 = self._获取字段值(原始协议包, "协议头.消息类型")
        
        if 数据类型 == "输出":
            原始协议包 = self._清洗协议包会话标识(原始协议包, 节点ID)
            # 1. 提取关键字段（协议包读取，不上锁）
            消息标识 = self._获取字段值(原始协议包, "协议头.消息标识")
            消息分片 = self._获取字段值(原始协议包, "协议尾.消息分片")
            目标节点 = self._获取字段值(原始协议包, "协议头.路由信息.目标节点")
            
