            # 4. 初始节点处理（协议包修改，不上锁）
            当前初始节点 = self._获取字段值(原始协议包, "协议头.路由信息.初始节点")
            if not isinstance(当前初始节点, str) or not 当前初始节点:
                创建者节点 = 会话.创建者节点 if 会话 else (节点ID or "系统")
